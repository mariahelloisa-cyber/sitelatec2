## Objetivo do Curso
O principal objetivo do EJA 2.0 é possibilitar a conclusão do Ensino Fundamental e do Ensino Médio para jovens e adultos que desejam regularizar sua vida escolar e ampliar suas oportunidades acadêmicas e profissionais.

Ao concluir o programa, o aluno estará apto a:

comprovar escolaridade;
