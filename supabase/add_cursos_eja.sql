## Metodologia de Ensino
O aluno estudará por meio de uma plataforma de ensino moderna e intuitiva, com acesso a diversos recursos acadêmicos, como:

Videoaulas;
Apostilas digitais;
Exercícios e atividades;
Conteúdos complementares;
Biblioteca digital;
Materiais de apoio.

