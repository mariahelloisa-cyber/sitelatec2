-- ============================================================
-- 11) STORAGE: bucket público "banners"
-- Usado por TODOS os uploads de imagem do painel admin
-- (banners, selos, depoimentos, diferenciais, notícias,
--  cursos em destaque, banner lateral e foto de Nossa História).
-- ============================================================
insert into storage.buckets (id, name, public)
values ('banners', 'banners', true)
on conflict (id) do nothing;

drop policy if exists "banners bucket: leitura publica" on storage.objects;
create policy "banners bucket: leitura publica"
  on storage.objects for select
  to public
  using (bucket_id = 'banners');

drop policy if exists "banners bucket: upload autenticado" on storage.objects;
create policy "banners bucket: upload autenticado"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'banners');

drop policy if exists "banners bucket: delete autenticado" on storage.objects;
create policy "banners bucket: delete autenticado"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'banners');

