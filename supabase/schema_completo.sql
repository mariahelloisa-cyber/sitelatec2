alter table public.banners enable row level security;
drop policy if exists "banners: leitura publica" on public.banners;
create policy "banners: leitura publica" on public.banners for select to anon, authenticated using (true);
drop policy if exists "banners: insert autenticado" on public.banners;
create policy "banners: insert autenticado" on public.banners for insert to authenticated with check (true);
drop policy if exists "banners: delete autenticado" on public.banners;
create policy "banners: delete autenticado" on public.banners for delete to authenticated using (true);

